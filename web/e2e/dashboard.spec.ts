import { expect, test } from '@playwright/test'
import { fixture, streamStats } from './fixtures'

test('mantém a navegação temporal, a identidade dos recursos e os estados históricos', async ({ page }) => {
  const { requests } = await fixture(page)
  await page.goto('/overview?range=15m')
  await expect(page.getByRole('heading', { name: 'Visão geral' })).toBeVisible()
  await expect(page.getByText('edge-01').last()).toBeVisible()
  await expect(page.getByText('Histórico parcial').first()).toBeVisible()
  const cpuPanel = page.getByRole('region', { name: 'Utilização da CPU' })
  const slider = cpuPanel.getByRole('slider')
  await slider.focus()
  await slider.press('ArrowLeft')
  await slider.press('ArrowLeft')
  await expect(cpuPanel.getByText('Sem amostra neste intervalo.')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Uso de memória' }).getByText('Sem amostra neste intervalo.')).toBeVisible()
  await slider.press('ArrowLeft')
  await expect(slider).toHaveAttribute('aria-valuetext', /UTC · 0%/)
  const line = await cpuPanel.locator('[data-history-line]').getAttribute('d')
  expect(line?.match(/M/g)?.length).toBe(2)
  expect(requests.some(url => url.searchParams.get('step') === 'auto' && url.searchParams.get('max_points') === '600')).toBe(true)

  await page.getByRole('button', { name: '7d' }).click()
  await expect(cpuPanel.getByText('Resolução 1h')).toBeVisible()
  await page.getByRole('link', { name: 'Host' }).click()
  await expect(page).toHaveURL('/host/cpu?range=7d')
  const cores = page.getByRole('table', { name: 'Núcleos da CPU' })
  await expect(cores.getByRole('row', { name: /cpu9/ })).toContainText('cpu:9')
  await expect(cores.getByRole('row', { name: /cpu9/ })).toContainText('0%')
  await expect(cores.getByRole('row', { name: /cpu22/ })).toContainText('Inativo')
  await cores.getByRole('button', { name: 'Recurso' }).focus()
  await cores.getByRole('button', { name: 'Recurso' }).press('Enter')
  await expect(cores.getByRole('columnheader', { name: 'Recurso' })).toHaveAttribute('aria-sort', 'descending')

  const cpu = page.getByRole('tab', { name: 'CPU' })
  await cpu.focus()
  await cpu.press('ArrowRight')
  await expect(page).toHaveURL('/host/memory?range=7d')
  await expect(page.getByRole('tab', { name: 'Memória' })).toBeFocused()
  await expect(page.getByRole('region', { name: 'Uso de swap' }).getByText(/Sem amostras neste período/)).toBeVisible()
  await page.goBack()
  await expect(cpu).toHaveAttribute('aria-selected', 'true')
  await page.goForward()
  await expect(page.getByRole('tab', { name: 'Memória' })).toHaveAttribute('aria-selected', 'true')

  await page.getByRole('tab', { name: 'Armazenamento' }).click()
  const mounts = page.getByRole('table', { name: 'Capacidade dos sistemas de arquivos' })
  await expect(mounts.getByRole('row')).toHaveCount(3)
  await expect(page.getByRole('table', { name: 'I/O dos dispositivos de bloco' }).getByRole('row')).toHaveCount(3)
  await mounts.getByRole('link', { name: '/data' }).click()
  await expect(page).toHaveURL(/range=7d&resource=fs%3Adata/)
  await expect(page.getByText('fs:data', { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Utilização da montagem' })).toBeVisible()

  await page.getByRole('tab', { name: 'Rede' }).click()
  const nics = page.getByRole('table', { name: 'Interfaces de rede' })
  await expect(nics.getByRole('row', { name: /enp1s0/ })).toContainText('8 KiB/s')
  await expect(nics.getByRole('row', { name: /porta-renomeada/ })).toContainText('512 B/s')
  await nics.getByRole('link', { name: 'porta-renomeada' }).click()
  await page.reload()
  await expect(page).toHaveURL(/range=7d&resource=nic%3A2/)
  await expect(page.getByRole('heading', { name: 'porta-renomeada' })).toBeVisible()
  await page.getByLabel('Buscar recurso').fill('sem correspondência')
  await expect(page.getByText('Nenhum recurso corresponde aos filtros.')).toBeVisible()

  await page.getByRole('tab', { name: 'Sensores' }).click()
  await expect(page.getByRole('row', { name: /Canal zero/ })).toContainText('0 °C')
  await expect(page.getByRole('row', { name: /Canal sem leitura/ })).toContainText('Sem leitura recente')
})

