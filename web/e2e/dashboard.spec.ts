test('distingue atraso e reconexão e encerra a conexão ao receber 401', async ({ page }) => {
  const clock = new Date()
  await page.clock.install({ time: clock })
  const api = await fixture(page)
  await page.goto('/overview')
  const status = page.getByRole('banner').getByRole('status')
  await expect(status).toHaveText('Ao vivo')
  expect(await streamStats(page)).toEqual({ starts: 1, open: 1, max: 1 })
  await page.clock.fastForward(23_000)
  await expect(status).toHaveText('Leituras atrasadas')
  await expect(page.getByText(/Leitura atrasada ·/).first()).toBeVisible()

  const historyBefore = api.requests.filter(url => url.pathname.endsWith('/metrics')).length
  await page.evaluate(() => window.dispatchEvent(new Event('fixture-drop')))
  await expect(status).toHaveText('Reconectando')
  await page.clock.fastForward(1500)
  await expect(status).toHaveText('Ao vivo')
  await expect.poll(() => api.requests.filter(url => url.pathname.endsWith('/metrics')).length).toBeGreaterThan(historyBefore)
  expect(await streamStats(page)).toEqual({ starts: 2, open: 1, max: 1 })

  api.expire()
  await page.getByRole('button', { name: '6h' }).click()
  await expect(page).toHaveURL('/login')
  await expect(page.getByText(/Sua sessão expirou/)).toBeVisible()
  expect((await streamStats(page)).open).toBe(0)
})

test('compartilha a janela UTC personalizada com o detalhe do recurso', async ({ page }) => {
  const api = await fixture(page)
  await page.goto('/overview')
  await page.getByRole('button', { name: 'Personalizado' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Início (UTC)').fill('2026-11-20T11:00')
  await dialog.getByLabel('Fim (UTC)').fill('2026-11-20T10:00')
  await dialog.getByRole('button', { name: 'Aplicar' }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await dialog.getByLabel('Fim (UTC)').fill('2026-11-20T12:00')
  await dialog.getByRole('button', { name: 'Aplicar' }).click()
  const from = String(Date.parse('2026-11-20T11:00Z'))
  const to = String(Date.parse('2026-11-20T12:00Z'))
  await expect(page).toHaveURL('/overview?range=custom&from=' + from + '&to=' + to)
  await expect.poll(() => api.requests.some(url => url.pathname.endsWith('/metrics') && url.searchParams.get('from') === from)).toBe(true)

  await page.getByRole('link', { name: 'Host' }).click()
  await page.getByRole('tab', { name: 'Rede' }).click()
  await page.getByRole('link', { name: 'enp1s0' }).click()
  await expect(page).toHaveURL('/host/network?range=custom&from=' + from + '&to=' + to + '&resource=nic%3A1')
  await page.getByRole('button', { name: '24h' }).click()
  await expect(page).toHaveURL('/host/network?resource=nic%3A1&range=24h')
})
